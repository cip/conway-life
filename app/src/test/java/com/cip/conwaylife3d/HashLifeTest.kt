package com.cip.conwaylife3d
import org.junit.Assert.*
import org.junit.Test
import kotlin.random.Random
class HashLifeTest {
    private val slow=SparseLife()
    @Test fun gliderAndOscillators() {
        val examples=listOf(
          setOf(Cell(1,0),Cell(2,1),Cell(0,2),Cell(1,2),Cell(2,2)),
          setOf(Cell(47,47),Cell(48,47),Cell(49,47)),
          setOf(Cell(-2,-2),Cell(-1,-2),Cell(-2,-1),Cell(-1,-1)))
        for(p in examples)for(n in listOf(0,1,2,3,4,8,16,32,64)){
            var expected=p
            repeat(n){expected=slow.next(expected)}
            assertEquals("generation $n",expected,HashLife().advance(p,n))
        }
    }
    @Test fun seededRandomWorldsAgree() {
        val random=Random(12345)
        repeat(15){
            val input=buildSet{
                for(y in -5..5)for(x in -5..5)if(random.nextInt(5)==0)add(Cell(x,y))
            }
            val generations=random.nextInt(1,25)
            var expected=input
            repeat(generations){expected=slow.next(expected)}
            assertEquals("random scenario $it",expected,HashLife().advance(input,generations))
        }
    }
    @Test fun emptyAndZero() {
        assertTrue(HashLife().advance(emptySet(),1000).isEmpty())
        val c=setOf(Cell(0,0))
        assertEquals(c,HashLife().advance(c,0))
    }
    /**
     * Large-generation reference from the known B3/S23 glider period:
     * exactly four generations translate the five live cells by (+1,+1).
     * The expected answer is analytical, not generated by the HashLife engine.
     */
    @Test fun full16384JumpPreservesKnownGliderSignal() {
        val glider=setOf(Cell(1,0),Cell(2,1),Cell(0,2),Cell(1,2),Cell(2,2))
        val input=glider.map { Cell(it.x-5000,it.y-7000) }.toSet()
        val displacement=16384/4
        val expected=input.map { Cell(it.x+displacement,it.y+displacement) }.toSet()
        assertEquals(expected,HashLife().advance(input,16384))
    }

    /** The bottom region must not acquire spurious cells for a stable block. */
    @Test fun bottomRegionIsEmptyWhenTheSourceIsStationary() {
        val block=setOf(Cell(0,0),Cell(1,0),Cell(0,1),Cell(1,1))
        assertEquals(block,HashLife().advance(block,1024))
    }

    /** Every cell (not just population) must match the independent sparse stepper. */
    @Test fun negativeCoordinatesAndMultipleGenerationSizesAgree() {
        val seed=setOf(Cell(-30,97),Cell(-29,97),Cell(-28,97),
                       Cell(7,-43),Cell(8,-42),Cell(6,-41),Cell(7,-41),Cell(8,-41))
        for(steps in listOf(1,2,3,7,15,31,64,128)) {
            var expected=seed
            repeat(steps) { expected=slow.next(expected) }
            assertEquals("mismatch at generation $steps",expected,HashLife().advance(seed,steps))
        }
    }

}
